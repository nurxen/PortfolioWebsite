function changeLanguageIndex(lang) {
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");
        if (translationsIndex[lang] && translationsIndex[lang][key]) {
            element.textContent = translationsIndex[lang][key];
        }
    });

    // Traducir meta descripción si existe
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && translationsIndex[lang]["meta_desc"]) {
        metaDesc.setAttribute("content", translationsIndex[lang]["meta_desc"]);
    }

    // Traducir título de la pestaña
    if (translationsIndex[lang]["meta_title"]) {
        document.title = translationsIndex[lang]["meta_title"];
    }

    localStorage.setItem("preferred_lang", lang);
    const btn = document.getElementById("lang-toggle");
    if (btn) {
        btn.textContent = lang === "es" ? "EN" : "ES";
    }
}

document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("preferred_lang") || "en";
    if (savedLang === "es") {
        changeLanguageIndex("es");
    }

    const toggleBtn = document.getElementById("lang-toggle");
    if (toggleBtn) {
        toggleBtn.addEventListener("click", () => {
            const currentLang = localStorage.getItem("preferred_lang") || "en";
            const newLang = currentLang === "en" ? "es" : "en";
            changeLanguageIndex(newLang);
        });
    }
});